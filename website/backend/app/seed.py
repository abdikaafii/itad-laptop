"""Demonstration data for development. Everything created here is flagged is_demo and is built from
the simulator, never from a real device. Passwords are random and written to a file that is not
committed (instance/demo_credentials.txt)."""
import os
import secrets
from datetime import datetime, timedelta, timezone

from .core.db import one, run, utcnow
from .core.security import hash_password, sha256_hex
from .integrations import simulator
from .integrations.engine import ingest_report
from .certificates.service import eligible_erasures, issue_certificate

DEMO_COMPANY = "Harbour ITAD (DEMONSTRATION DATA)"


def _pw():
    return secrets.token_urlsafe(10) + "Aa1"


def _user(cid, email, name, role, pw, customer_id=None):
    return run("INSERT INTO users (company_id, customer_id, email, full_name, role, password_hash, email_verified, "
               "created_at) VALUES (?,?,?,?,?,?,1,?)",
               (cid, customer_id, email, name, role, hash_password(pw), utcnow()))


def _demo_key(instance_dir):
    from cryptography.hazmat.primitives import serialization
    path = os.path.join(instance_dir, "demo_signing_key.pem")
    if os.path.exists(path):
        with open(path, "rb") as f:
            return serialization.load_pem_private_key(f.read(), None)
    key = simulator.new_demo_key()
    os.makedirs(instance_dir, exist_ok=True)
    with open(path, "wb") as f:
        f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                  serialization.NoEncryption()))
    os.chmod(path, 0o600)
    return key


def seed_demo(instance_dir):
    """Create the demo company. Must run inside an app context. Returns a dict of credentials."""
    if one("SELECT 1 FROM companies WHERE name = ?", (DEMO_COMPANY,)):
        raise RuntimeError("Demo data already exists. Delete the database file to start again.")
    now = utcnow()
    cid = run("INSERT INTO companies (name, legal_name, address, email, phone, website, certificate_footer, "
              "is_demo, created_at) VALUES (?,?,?,?,?,?,?,1,?)",
              (DEMO_COMPANY, "Harbour ITAD Ltd (demo)", "1 Example Quay, Dublin, Ireland", "demo@example.invalid",
               "+353 1 000 0000", "https://example.invalid",
               "DEMONSTRATION DATA: generated by the development simulator. Not a real erasure.", now))
    creds = {}
    users = {}
    for key, email, name, role in (("admin", "admin@harbour-demo.example", "Aoife Admin", "company_admin"),
                                   ("tech1", "ali@harbour-demo.example", "Ali Hassan", "technician"),
                                   ("tech2", "carl@harbour-demo.example", "Carl Murphy", "technician")):
        pw = _pw()
        users[key] = _user(cid, email, name, role, pw)
        creds[key] = (email, pw)

    customers = {}
    for key, name in (("bank", "Northgate Bank (DEMO)"), ("council", "Westfield Council (DEMO)")):
        customers[key] = run("INSERT INTO customers (company_id, name, contact_name, contact_email, created_at) "
                             "VALUES (?,?,?,?,?)", (cid, name, "Demo Contact", "contact@example.invalid", now))
    for key, email, name, cust in (("cust_bank", "it@northgate-demo.example", "Niamh Northgate", "bank"),
                                   ("cust_council", "it@westfield-demo.example", "Wes Westfield", "council")):
        pw = _pw()
        _user(cid, email, name, "customer", pw, customer_id=customers[cust])
        creds[key] = (email, pw)

    key = _demo_key(instance_dir)
    pub = simulator.public_hex(key)
    import hashlib
    run("INSERT INTO signing_keys (company_id, key_id, public_key_hex, label, is_demo, created_at) "
        "VALUES (?,?,?,?,1,?)", (cid, hashlib.sha256(bytes.fromhex(pub)).hexdigest()[:16], pub,
                                 "DEMO simulator key", now))
    token = "itad_" + secrets.token_urlsafe(32)
    run("INSERT INTO api_tokens (company_id, name, token_hash, prefix, created_at) VALUES (?,?,?,?,?)",
        (cid, "Demo station", sha256_hex(token), token[:9], now))
    creds["api_token"] = ("demo station", token)

    jobs = {}
    for ref, title, cust, tech, status, n in (
            ("DEMO-J-1001", "Northgate branch refresh", "bank", "tech1", "in_progress", 8),
            ("DEMO-J-1002", "Westfield council laptops", "council", "tech2", "in_progress", 6),
            ("DEMO-J-1003", "Northgate head office (finished)", "bank", "tech1", "completed", 5),
            ("DEMO-J-1004", "Westfield spring collection", "council", "tech2", "open", 10)):
        jobs[ref] = run("INSERT INTO jobs (company_id, customer_id, job_ref, title, status, assigned_technician_id, "
                        "expected_assets, created_by, created_at, completed_at, is_demo) VALUES (?,?,?,?,?,?,?,?,?,?,1)",
                        (cid, customers[cust], ref, title, status, users[tech], n, users["admin"], now,
                         now if status == "completed" else ""))

    plan = []
    scen = ["pass", "pass", "pass", "pass", "pass", "incomplete", "test_fail", "pass", "wipe_failed", "pass",
            "pass", "not_verified", "pass", "pass", "unsigned", "pass", "test_mode", "pass", "pass", "pass"]
    refs = ["DEMO-J-1001"] * 8 + ["DEMO-J-1002"] * 5 + ["DEMO-J-1003"] * 5 + ["DEMO-J-1002"] * 2
    techs = {"DEMO-J-1001": "Ali Hassan", "DEMO-J-1002": "Carl Murphy", "DEMO-J-1003": "Ali Hassan"}
    today = datetime.now(timezone.utc).replace(tzinfo=None).replace(hour=9, minute=0, second=0, microsecond=0)
    for i, sc in enumerate(scen):
        ref = refs[i]
        plan.append((ref, "DEMO-A-%04d" % (i + 1), "DEMOSN%06d" % (4100 + i * 37), techs[ref], sc, i))
    issued = 0
    admin_user = one("SELECT * FROM users WHERE id = ?", (users["admin"],))
    for ref, tag, serial, tech, sc, i in plan:
        when = today - timedelta(days=(len(plan) - i) * 1.2)
        rep = simulator.make_report(key, ref, tag, serial, tech, scenario=sc, model_index=i, when=when)
        res = ingest_report(cid, rep, source="demo")
        stamp = when.strftime("%Y-%m-%d %H:%M:%S")
        run("UPDATE assets SET created_at = ?, processed_at = ?, updated_at = ? WHERE id = ?",
            (stamp, stamp, stamp, res["asset_id"]))
        run("UPDATE engine_reports SET received_at = ? WHERE id = ?", (stamp, res["report_id"]))
        # Issue certificates for most clean ones, leave a couple waiting so the button can be tried.
        if sc == "pass" and i % 4 != 3:
            el = eligible_erasures(res["asset_id"])
            if el["ok"]:
                for er in el["erasures"]:
                    issue_certificate(er["id"], user=admin_user)
                    issued += 1
    # Pre-registered laptops that have not been processed yet
    for n in range(3):
        run("INSERT INTO assets (company_id, customer_id, job_id, asset_tag, serial, manufacturer, model, status, "
            "technician_id, technician_name, is_demo, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?,?,?,1,?,?)",
            (cid, customers["council"], jobs["DEMO-J-1004"], "DEMO-A-90%02d" % n, "DEMOSN9%05d" % n, "Dell",
             "Latitude 7420", "registered", users["tech2"], "Carl Murphy", now, now))
    creds["_company_id"] = cid
    creds["_certificates"] = issued
    return creds


def write_credentials(creds, path):
    lines = ["DEMONSTRATION LOGINS (random, generated once). Do not use for real data.", ""]
    labels = {"admin": "Company administrator", "tech1": "Technician (Ali)", "tech2": "Technician (Carl)",
              "cust_bank": "Customer: Northgate Bank", "cust_council": "Customer: Westfield Council",
              "api_token": "Engine API token"}
    for k, label in labels.items():
        who, secret = creds[k]
        lines.append("%-28s %s   %s" % (label, who, secret))
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    os.chmod(path, 0o600)
