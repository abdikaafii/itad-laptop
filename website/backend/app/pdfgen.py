NAVY = colors.HexColor("#07142B")
BLUE = colors.HexColor("#2E9BFF")
CYAN = colors.HexColor("#38BDF8")
INK = colors.HexColor("#0B1F40")
GREY = colors.HexColor("#5B6B84")
LINE = colors.HexColor("#D5DEEA")
SOFT = colors.HexColor("#F3F6FB")
STATUS_BG = {"PASS": "#DDF5EA", "FAIL": "#FBE1E1", "WARN": "#FFF3D1", "N/A": "#ECEFF4", "NOT TESTED": "#FFF3D1",
             "VALID": "#DDF5EA", "REVOKED": "#FBE1E1", "INVALID": "#FBE1E1", "DEMONSTRATION": "#FFF3D1",
             "INCOMPLETE": "#FFF3D1", "BLOCKED": "#FBE1E1"}
STATUS_FG = {"PASS": "#13774D", "FAIL": "#B3261E", "WARN": "#8A5A00", "N/A": "#5B6B84", "NOT TESTED": "#8A5A00",
             "VALID": "#13774D", "REVOKED": "#B3261E", "INVALID": "#B3261E", "DEMONSTRATION": "#8A5A00",
             "INCOMPLETE": "#8A5A00", "BLOCKED": "#B3261E"}


def _ps(name, size=9, bold=False, color=INK, lead=None, align=0):
    return ParagraphStyle(name, fontName="Helvetica-Bold" if bold else "Helvetica", fontSize=size,
                          leading=lead or size * 1.3, textColor=color, alignment=align)


S_TXT, S_SMALL = _ps("t", 8.6), _ps("s", 7.2, color=GREY)
S_KEY, S_VAL, S_H = _ps("k", 7.4, True, GREY), _ps("v", 9, True), _ps("h", 11, True)


def esc(v):
    return (str(v if v not in (None, "") else "-").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def _logo(company):
    data = (company or {}).get("logo_data") or ""
    m = re.match(r"data:image/(png|jpeg|jpg);base64,(.+)$", data, re.S)
    if not m:
        return None
    try:
        return ImageReader(io.BytesIO(base64.b64decode(m.group(2))))
    except Exception:
        return None


def _qr(c, x, y, size, text):
    w = QrCodeWidget(text)
    b = w.getBounds()
    d = Drawing(size, size, transform=[size / (b[2] - b[0]), 0, 0, size / (b[3] - b[1]), 0, 0])
    d.add(w)
    renderPDF.draw(d, c, x, y)


class QR(Flowable):
    """QR code as a flowable."""

    def __init__(self, url, size=30 * mm):
        super().__init__()
        self.url, self.width, self.height = url, size, size

    def draw(self):
        _qr(self.canv, 0, 0, self.width, self.url)


def _chrome(company, title, subtitle, demo=False, footer=""):
    """Page decoration shared by every document."""
    def draw(c, doc):
        W, H = doc.pagesize
        c.saveState()
        c.setFillColor(NAVY)
        c.rect(0, H - 28 * mm, W, 28 * mm, stroke=0, fill=1)
        c.setFillColor(BLUE)
        c.rect(0, H - 28 * mm, W, 1.2 * mm, stroke=0, fill=1)
        x = 14 * mm
        lg = _logo(company)
        if lg:
            c.drawImage(lg, x, H - 23 * mm, 18 * mm, 18 * mm, preserveAspectRatio=True, mask="auto")
            x += 22 * mm
        c.setFillColor(colors.white)
        c.setFont("Helvetica-Bold", 17)
        c.drawString(x, H - 13 * mm, (company or {}).get("name") or config.PRODUCT_NAME)
        c.setFont("Helvetica", 8.5)
        c.setFillColor(CYAN)
        c.drawString(x, H - 19 * mm, "TEST  .  WIPE  .  VERIFY  .  CERTIFY")
        c.setFillColor(colors.white)
        c.setFont("Helvetica-Bold", 12)
        c.drawRightString(W - 14 * mm, H - 12 * mm, title)
        c.setFont("Helvetica", 8.5)
        c.drawRightString(W - 14 * mm, H - 18 * mm, subtitle)
        c.setFillColor(GREY)
        c.setFont("Helvetica", 7)
        c.drawString(14 * mm, 9 * mm, footer or "Generated by %s. Times are Europe/Dublin." % config.PRODUCT_NAME)
        c.drawRightString(W - 14 * mm, 9 * mm, "Page %d" % doc.page)
        if demo:
            c.setFillColor(colors.Color(0.85, 0.2, 0.2, alpha=0.10))
            c.setFont("Helvetica-Bold", 64)
            c.translate(W / 2, H / 2)
            c.rotate(35)
            c.drawCentredString(0, 0, "DEMONSTRATION")
        c.restoreState()
    return draw


def _kv_table(rows, width, cols=2):
    cells, line = [], []
    for k, v in rows:
        line.append([Paragraph(esc(k).upper(), S_KEY), Paragraph(esc(v), S_VAL)])
        if len(line) == cols:
            cells.append(line)
            line = []
    if line:
        while len(line) < cols:
            line.append(["", ""])
        cells.append(line)
    flat = [[Table([[c[0]], [c[1]]], colWidths=[width / cols - 4 * mm]) if c[0] != "" else "" for c in row] for row in cells]
    t = Table(flat, colWidths=[width / cols] * cols)
    t.setStyle(TableStyle([("BOX", (0, 0), (-1, -1), 0.5, LINE), ("INNERGRID", (0, 0), (-1, -1), 0.5, LINE),
                           ("BACKGROUND", (0, 0), (-1, -1), SOFT), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                           ("LEFTPADDING", (0, 0), (-1, -1), 4), ("TOPPADDING", (0, 0), (-1, -1), 2),
                           ("BOTTOMPADDING", (0, 0), (-1, -1), 2)]))
    return t


def _badge(text, w=36 * mm):
    t = Table([[Paragraph("<b>%s</b>" % esc(text), _ps("b", 12, True, colors.HexColor(STATUS_FG.get(text, "#13774D")), align=1))]],
              colWidths=[w], rowHeights=[9 * mm])
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(STATUS_BG.get(text, "#DDF5EA"))),
                           ("VALIGN", (0, 0), (-1, -1), "MIDDLE")]))
    return t


def _status_cell(s):
    return Paragraph("<font color='%s'><b>%s</b></font>" % (STATUS_FG.get(s, "#0B1F40"), esc(s)), _ps("sc", 8, True))


def _build(buf, pagesize, story, chrome, margins=(14, 34, 14, 16)):
    doc = SimpleDocTemplate(buf, pagesize=pagesize, leftMargin=margins[0] * mm, topMargin=margins[1] * mm,
                            rightMargin=margins[2] * mm, bottomMargin=margins[3] * mm,
                            title=chrome.__doc__ or "ITAD document", author=config.PRODUCT_NAME)
    doc.build(story, onFirstPage=chrome, onLaterPages=chrome)
    return buf.getvalue()


# ============================================================ certificate PDF
def certificate_pdf(cert, company, state):
    """cert = certificates row; state = services.certificate_status()."""
    p = json.loads(cert["payload"])
    demo = bool(cert["demo"])
    chrome = _chrome(company, "Certificate of Data Erasure", p["number"], demo,
                     "Verify at %s/verify/%s  .  Times are Europe/Dublin." % (config.PUBLIC_BASE_URL, p["number"]))
    W = A4[0] - 28 * mm
    story = []
    top = Table([[[Paragraph("CERTIFICATE NUMBER", S_KEY), Paragraph("<b>%s</b>" % esc(p["number"]), _ps("n", 15, True)),
                   Spacer(1, 2 * mm), Paragraph("ISSUED", S_KEY), Paragraph(esc(p["issued_at_dublin"]), S_VAL)],
                  _badge(state["state"], 42 * mm)]], colWidths=[W - 46 * mm, 44 * mm])
    top.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "MIDDLE")]))
    story += [top, Spacer(1, 4 * mm)]
    if state["state"] == "REVOKED":
        story += [Paragraph("<font color='#B3261E'><b>This certificate was revoked on %s. Reason: %s</b></font>" % (
            esc(state["revoked_at"]), esc(state["revoked_reason"])), S_TXT), Spacer(1, 3 * mm)]
    if demo:
        story += [Paragraph("<font color='#8A5A00'><b>DEMONSTRATION DATA. This certificate is not a record of a real erasure.</b></font>", S_TXT),
                  Spacer(1, 3 * mm)]
    st, er = p["storage"], p["erasure"]
    for title, rows in [
        ("Customer and job", [("Customer", p["customer"]), ("Job reference", p["job_ref"])]),
        ("Device", [("Manufacturer", p["asset"]["manufacturer"]), ("Model", p["asset"]["model"]),
                    ("Serial number", p["asset"]["serial"]), ("Asset ID", p["asset"]["tag"])]),
        ("Storage device", [("Drive", st["device"]), ("Model", st["model"]), ("Serial", st["serial"]),
                            ("Capacity (GB)", st["capacity_gb"])]),
        ("Sanitisation", [("Method", er["method"]), ("Standard", er["standard"]), ("Passes", er["passes"]),
                          ("Erasure ID (engine)", er["engine_ref"]), ("Started", er["started"]), ("Finished", er["finished"])]),
        ("Verification and technician", [("Verification result", er["status"]), ("Verified by read-back", "Yes" if er["verified"] else "No"),
                                         ("Technician", p["technician"]), ("Issued (Dublin)", p["issued_at_dublin"])]),
    ]:
        story += [Paragraph(title, S_H), Spacer(1, 1 * mm), _kv_table(rows, W), Spacer(1, 2 * mm)]
    sr = p.get("source_report")
    sig = ("Source engine report SHA-256 %s, signed by key %s (%s)." % (
        sr["sha256"][:24] + "...", sr["signing_key"], "trusted" if sr["key_trusted"] else "not in the trusted list")) if sr else "Demonstration record."
    foot = Table([[[Paragraph("Certificate verification", S_H), Spacer(1, 1 * mm),
                    Paragraph("Scan the code or open %s/verify/%s to check this certificate is genuine and has not been changed or revoked." %
                              (config.PUBLIC_BASE_URL, esc(p["number"])), S_TXT), Spacer(1, 1 * mm),
                    Paragraph("Platform signature (Ed25519): key %s, content hash %s..." % (cert["key_id"], cert["payload_sha256"][:24]), S_SMALL),
                    Paragraph(sig, S_SMALL)], QR("%s/verify/%s" % (config.PUBLIC_BASE_URL, p["number"]))]],
                 colWidths=[W - 36 * mm, 34 * mm], rowHeights=[34 * mm])
    foot.setStyle(TableStyle([("BOX", (0, 0), (-1, -1), 0.6, LINE), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story.append(KeepTogether([foot]))
    return _build(io.BytesIO(), A4, story, chrome)


# =============================================================== asset report
def asset_report_pdf(data, company):
    """data: dict from api.asset_detail (asset, erasures, tests, inspection, assessment, job, customer)."""
    a, ass = data["asset"], data["assessment"]
    demo = bool(a["demo"])
    chrome = _chrome(company, "Laptop Processing Report", a["asset_tag"], demo)
    W = A4[0] - 28 * mm
    story = [Table([[[Paragraph("OVERALL RESULT", S_KEY), Paragraph("%s" % esc(a["serial"]), S_VAL)], _badge(ass["overall"], 42 * mm)]],
                   colWidths=[W - 46 * mm, 44 * mm]), Spacer(1, 3 * mm)]
    for r in ass["reasons"]:
        story.append(Paragraph("- %s" % esc(r), S_TXT))
    story.append(Spacer(1, 3 * mm))
    story += [Paragraph("Asset", S_H), Spacer(1, 1.5 * mm), _kv_table([
        ("Asset ID", a["asset_tag"]), ("Serial", a["serial"]), ("Manufacturer", a["manufacturer"]), ("Model", a["model"]),
        ("CPU", a["cpu"]), ("RAM", a["ram_gb"]), ("Storage", a["storage_summary"]), ("BIOS", a["bios"]),
        ("Operating system", a["os_info"]), ("Customer", (data.get("customer") or {}).get("name")),
        ("Job", (data.get("job") or {}).get("job_ref")), ("Technician", data.get("technician_name"))], W, 3), Spacer(1, 4 * mm)]
    insp = data.get("inspection")
    if insp:
        story += [Paragraph("Initial inspection", S_H), Spacer(1, 1.5 * mm), _kv_table([
            ("Pre-wipe check", insp["check_result"]), ("Absolute", insp["absolute_result"]),
            ("Enrolment", insp["enrolment_result"]), ("Cosmetic grade", insp["cosmetic_grade"]),
            ("Issues", ", ".join(json.loads(insp["issues"] or "[]")) or "none"), ("Notes", insp["notes"])], W, 3), Spacer(1, 4 * mm)]
    story.append(Paragraph("Data erasure", S_H))
    story.append(Spacer(1, 1.5 * mm))
    rows = [[Paragraph(h, S_KEY) for h in ("DRIVE", "METHOD", "STANDARD", "RESULT", "VERIFIED", "FINISHED")]]
    for e in data["erasures"]:
        rows.append([Paragraph(esc("%s %s" % (e["device_path"] or "", e["model"] or "")), S_TXT), Paragraph(esc(e["method"]), S_TXT),
                     Paragraph(esc(e["standard"]), S_TXT), _status_cell("PASS" if e["status"] == "Success" else "FAIL" if e["status"] == "Failed" else "WARN"),
                     Paragraph("Yes" if e["verified"] else "No", S_TXT), Paragraph(esc(e["finished"]), S_TXT)])
    if len(rows) == 1:
        rows.append([Paragraph("No erasure recorded", S_TXT)] + [""] * 5)
    t = Table(rows, colWidths=[W * .2, W * .24, W * .2, W * .1, W * .1, W * .16], repeatRows=1)
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, LINE), ("BACKGROUND", (0, 0), (-1, 0), SOFT), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story += [t, Spacer(1, 4 * mm), Paragraph("Hardware tests", S_H), Spacer(1, 1.5 * mm)]
    rows = [[Paragraph(h, S_KEY) for h in ("COMPONENT", "RESULT", "NOTES")]]
    for comp in data["tests"]:
        rows.append([Paragraph(esc(comp["component"]), S_VAL), _status_cell(comp["status"]), Paragraph(esc(comp["notes"]), S_TXT)])
    t = Table(rows, colWidths=[W * .22, W * .14, W * .64], repeatRows=1)
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, LINE), ("BACKGROUND", (0, 0), (-1, 0), SOFT), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story += [t, Spacer(1, 4 * mm)]
    if data.get("certificates"):
        story.append(Paragraph("Certificates: " + ", ".join(c["number"] for c in data["certificates"]), S_TXT))
    return _build(io.BytesIO(), A4, story, chrome)


# ============================================================ table reports
def table_pdf(title, subtitle, columns, rows, company, summary=None):
    chrome = _chrome(company, title, subtitle)
    ps = landscape(A4)
    W = ps[0] - 28 * mm
    story = []
    if summary:
        story += [_kv_table(summary, W, min(4, len(summary))), Spacer(1, 4 * mm)]
    head = [Paragraph(esc(c).upper(), S_KEY) for c in columns]
    data = [head]
    for r in rows:
        data.append([_status_cell(str(v)) if str(v) in STATUS_FG and k in (len(r) - 1,) else Paragraph(esc(v), S_TXT)
                     for k, v in enumerate(r)])
    if len(data) == 1:
        data.append([Paragraph("No records for this selection.", S_TXT)] + [""] * (len(columns) - 1))
    t = Table(data, colWidths=[W / len(columns)] * len(columns), repeatRows=1)
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, LINE), ("BACKGROUND", (0, 0), (-1, 0), SOFT),
                           ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#FAFBFD")]),
                           ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story.append(t)
    return _build(io.BytesIO(), ps, story, chrome, margins=(14, 34, 14, 16))


def csv_bytes(columns, rows):
    out = io.StringIO()
    w = csv.writer(out)
    w.writerow(columns)
    for r in rows:
        # neutralise spreadsheet formula injection
        w.writerow([("'" + str(v)) if isinstance(v, str) and v[:1] in ("=", "+", "-", "@") else v for v in r])
    return out.getvalue().encode("utf-8-sig")
